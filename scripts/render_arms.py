#!/usr/bin/env python3
"""
Combine rendered per-tool readfish configs into one config that compares the
tools side by side on one flow cell (readfish fork, branch ak/parallel-arms).

    render_arms.py <config_dir> <dataset> <tool> [<tool>...] [--threads 2] [--output <toml>]

Reads <config_dir>/rf_<tool>_<dataset>.toml as written by render_configs.sh and
writes one region per tool, in the order given, followed by the control
region(s), with channel_assignment = "modulo": channel c goes to region
(c - 1) % N, so with 7 tools and a control every 8th channel runs the same
tool. Each tool's region:
  - takes its decisions from the non-control region of the shared policy
    (configs/regions/$REGIONS.toml, already appended to the rendered configs)
  - has the tool's mapper_settings, with threads/n_threads set to --threads
  - has the tool's caller_settings only if they differ from the shared caller
    (the most common one among the tools, e.g. dorado; raw-signal tools bring
    their own)
readfish runs every tool's region in its own worker process. Prints the
output path (default <config_dir>/rf_arms_<tool>-<tool>..._<dataset>.toml).
"""
import argparse
import sys
from collections import Counter
from pathlib import Path

import rtoml

THREAD_KEYS = ("threads", "n_threads")


def load(config_dir: Path, tool: str, dataset: str) -> dict:
    path = config_dir / f"rf_{tool}_{dataset}.toml"
    if not path.is_file():
        sys.exit(f"Error: {path} not found (run scripts/render_configs.sh first)")
    return rtoml.loads(path.read_text())


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[1],
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("config_dir", type=Path)
    parser.add_argument("dataset")
    parser.add_argument("tools", nargs="+")
    parser.add_argument("--threads", type=int, default=2,
                        help="threads per tool (threads/n_threads), default 2")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if len(set(args.tools)) != len(args.tools):
        sys.exit("Error: a tool is given twice")

    confs = {tool: load(args.config_dir, tool, args.dataset) for tool in args.tools}
    first = confs[args.tools[0]]
    policy = [r for r in first["regions"] if not r.get("control", False)]
    controls = [r for r in first["regions"] if r.get("control", False)]
    if len(policy) != 1:
        sys.exit(f"Error: expected one non-control region in the shared policy, found {len(policy)}")

    def key(settings):
        return rtoml.dumps(settings)

    # the caller most tools use becomes the top-level one
    callers = Counter(key(c["caller_settings"]) for c in confs.values())
    shared_caller = rtoml.loads(callers.most_common(1)[0][0])

    regions = []
    for tool, conf in confs.items():
        if [r for r in conf["regions"] if not r.get("control", False)] != policy:
            sys.exit(f"Error: {tool}'s config has a different policy than {args.tools[0]}'s")
        (plugin, params), = conf["mapper_settings"].items()
        for k in THREAD_KEYS:
            if k in params:
                params[k] = args.threads
        region = dict(policy[0], name=tool)
        if key(conf["caller_settings"]) != key(shared_caller):
            region["caller_settings"] = conf["caller_settings"]
        region["mapper_settings"] = {plugin: params}
        regions.append(region)

    header = (
        f"# {len(args.tools)} tools side by side ({', '.join(args.tools)}) and "
        f"{len(controls)} control region(s): channel c runs region (c - 1) % "
        f"{len(regions) + len(controls)}, in the order listed.\n"
        f"# Generated by scripts/render_arms.py from {args.config_dir}; needs readfish "
        f"from ratschlab/readfish ak/parallel-arms.\n\n"
    )
    output = args.output or args.config_dir / f"rf_arms_{'-'.join(args.tools)}_{args.dataset}.toml"
    # two dumps, so that the shared caller comes before the regions
    top = rtoml.dumps({"channel_assignment": "modulo", "caller_settings": shared_caller}, pretty=True)
    output.write_text(header + top + "\n" + rtoml.dumps({"regions": regions + controls}, pretty=True))
    print(output)


if __name__ == "__main__":
    main()
